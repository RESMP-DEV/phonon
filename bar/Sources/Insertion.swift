import AppKit
import ApplicationServices

struct InsertionTargetSnapshot: Equatable, Sendable {
    let processID: pid_t
    let bundleIdentifier: String?
    let localizedName: String?
    let focusedElementProcessID: pid_t?

    static func captureFrontmost() -> InsertionTargetSnapshot? {
        capture(NSWorkspace.shared.frontmostApplication)
    }

    static func capture(_ application: NSRunningApplication?) -> InsertionTargetSnapshot? {
        guard let application else { return nil }
        return InsertionTargetSnapshot(
            processID: application.processIdentifier,
            bundleIdentifier: application.bundleIdentifier,
            localizedName: application.localizedName,
            focusedElementProcessID: AXIsProcessTrusted()
                ? InsertionAccessibility.focusedElementProcessID()
                : nil
        )
    }

    func matches(_ current: InsertionTargetSnapshot) -> Bool {
        guard processID == current.processID else { return false }
        if let bundleIdentifier, !bundleIdentifier.isEmpty {
            guard let currentBundle = current.bundleIdentifier,
                  !currentBundle.isEmpty,
                  currentBundle == bundleIdentifier
            else { return false }
        }
        if let focusedElementProcessID,
           let currentFocused = current.focusedElementProcessID,
           focusedElementProcessID != currentFocused
        {
            return false
        }
        return true
    }
}

private enum InsertionAccessibility {
    static func focusedElementProcessID() -> pid_t? {
        let systemWide = AXUIElementCreateSystemWide()
        var focusedValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(
            systemWide, kAXFocusedUIElementAttribute as CFString, &focusedValue
        ) == .success else {
            return nil
        }

        var processID: pid_t = 0
        guard AXUIElementGetPid(focusedValue as! AXUIElement, &processID) == .success
        else {
            return nil
        }
        return processID
    }
}

enum InsertionTargetValidation: Equatable {
    case valid
    case missingExpectedTarget
    case missingCurrentTarget
    case changed(
        expectedProcessID: pid_t,
        currentProcessID: pid_t,
        expectedBundleIdentifier: String?,
        currentBundleIdentifier: String?)

    var isValid: Bool {
        self == .valid
    }

    static func validate(
        expected: InsertionTargetSnapshot?,
        current: InsertionTargetSnapshot?
    ) -> InsertionTargetValidation {
        guard let expected else { return .missingExpectedTarget }
        guard let current else { return .missingCurrentTarget }
        guard expected.matches(current) else {
            return .changed(
                expectedProcessID: expected.processID,
                currentProcessID: current.processID,
                expectedBundleIdentifier: expected.bundleIdentifier,
                currentBundleIdentifier: current.bundleIdentifier
            )
        }
        return .valid
    }
}

enum PasteboardPrivacy {
    static let markerTypeNames = [
        "org.nspasteboard.AutoGeneratedType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
    ]

    static func markerTypes() -> [NSPasteboard.PasteboardType] {
        markerTypeNames.map { NSPasteboard.PasteboardType($0) }
    }

    static func prepare(
        _ text: String,
        on pasteboard: NSPasteboard
    ) -> PasteboardTransaction? {
        let previous = PasteboardSnapshot.capture(from: pasteboard)
        pasteboard.clearContents()

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for markerType in markerTypes() {
            item.setString("", forType: markerType)
        }
        guard pasteboard.writeObjects([item]) else { return nil }
        return PasteboardTransaction(
            previous: previous, changeCount: pasteboard.changeCount)
    }
}

struct PasteboardSnapshot {
    let itemData: [[NSPasteboard.PasteboardType: Data]]

    static func capture(from pasteboard: NSPasteboard) -> PasteboardSnapshot {
        let itemData = (pasteboard.pasteboardItems ?? []).map { item in
            Dictionary(
                item.types.map { type in
                    (type, item.data(forType: type) ?? Data())
                },
                uniquingKeysWith: { first, _ in first }
            )
        }
        return PasteboardSnapshot(itemData: itemData)
    }

    func restore(on pasteboard: NSPasteboard) -> Bool {
        pasteboard.clearContents()
        let items = itemData.map { entries in
            let item = NSPasteboardItem()
            for (type, data) in entries {
                item.setData(data, forType: type)
            }
            return item
        }
        return items.isEmpty ? true : pasteboard.writeObjects(items)
    }
}

struct PasteboardTransaction {
    let previous: PasteboardSnapshot
    let changeCount: Int

    @discardableResult
    func restoreIfCurrent(on pasteboard: NSPasteboard) -> Bool {
        guard pasteboard.changeCount == changeCount else { return false }
        return previous.restore(on: pasteboard)
    }
}
